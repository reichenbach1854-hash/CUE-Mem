def adversarial_type_for_item(item: dict, has_relationship: bool) -> str:
    if item["expression_type"] == "implicit":
        types = [
            "implicit_overclaim",
            "person_owner_swap",
            "category_type_swap",
            "lexical_concept_swap",
            "polarity_flip",
            "false_presupposition",
            "event_context_swap",
            "attribute_slot_swap",
        ]
    else:
        types = [
            "person_owner_swap",
            "attribute_slot_swap",
            "category_type_swap",
            "lexical_concept_swap",
            "polarity_flip",
            "false_presupposition",
            "event_context_swap",
        ]
    selector = (item["p_id"] + item["pref_idx"] + CATEGORIES.index(item["category"])) % len(types)
    adv_type = types[selector]
    if adv_type == "person_owner_swap" and not has_relationship:
        return "attribute_slot_swap"
    return adv_type


def pick_balanced_adversarial_types(
    p_id: int,
    has_relationship: bool,
    expression_type: str,
    counters: dict[int, dict[str, int]],
    n: int = QAS_PER_PREF,
) -> list[str]:
    """Pick *n* distinct adversarial types, balancing per-person distribution.

    For each pick, choose the type with the lowest count for this person,
    breaking ties by the canonical order in ADVERSARIAL_TYPES.
    """
    if expression_type == "implicit":
        candidates = list(ADVERSARIAL_TYPES)
    else:
        candidates = [t for t in ADVERSARIAL_TYPES if t != "implicit_overclaim"]

    if not has_relationship:
        candidates = [t for t in candidates if t != "person_owner_swap"]

    person_counts = counters.setdefault(p_id, {t: 0 for t in ADVERSARIAL_TYPES})

    picked: list[str] = []
    for _ in range(n):
        available = [t for t in candidates if t not in picked]
        if not available:
            available = list(candidates)
        available.sort(key=lambda t: (person_counts[t], ADVERSARIAL_TYPES.index(t)))
        choice = available[0]
        picked.append(choice)
        person_counts[choice] += 1

    return picked


def _fallback_options(
    adv_answer: str, distractor1: str, distractor2: str, refusal_slot: int,
) -> tuple[dict, str]:
    ordered = [None] * 4
    ordered[refusal_slot] = REFUSAL_TEXT
    remaining = [i for i in range(4) if i != refusal_slot]
    ordered[remaining[0]] = adv_answer
    ordered[remaining[1]] = distractor1
    ordered[remaining[2]] = distractor2
    options = {label: ordered[idx] for idx, label in enumerate(OPTION_LABELS)}
    return options, OPTION_LABELS[refusal_slot]


def build_question_payload_fallback(
    base_question: str,
    item: dict,
    true_name: str,
    relationship_wrong_name: str | None,
    matched_events: list[dict],
    formatted_profile: dict,
    target_type: str,
    base_options: dict,
    base_answer: str,
    refusal_slot: int,
) -> dict:
    tail = subject_tail(base_question, item["subcategory"])
    category = item["category"]
    subcategory = item["subcategory"]
    wrong_object = false_object_for_category(category, subcategory)
    loaded = loaded_concept_for_category(category, subcategory)
    adv_type = target_type
    true_pref = item["preference"]

    base_adv_answer = str(base_options.get(base_answer, "")).strip()
    base_distractors = [
        str(base_options[l]).strip()
        for l in OPTION_LABELS
        if l != base_answer and str(base_options.get(l, "")).strip()
    ]
    while len(base_distractors) < 2:
        base_distractors.append("同领域但历史未支持的另一选项")

    payload: dict = {
        "adversarial_type": adv_type,
        "Q": "",
        "options": {},
        "A": "",
        "adversarial_answer": "",
        "trap_reason": "",
        "reasonable_answer": "",
    }

    if adv_type == "person_owner_swap":
        payload["Q"] = f"{relationship_wrong_name}{tail}"
        opts, ans = _fallback_options(base_adv_answer, base_distractors[0], base_distractors[1], refusal_slot)
        payload["options"] = opts
        payload["A"] = ans
        payload["adversarial_answer"] = base_adv_answer
        payload["trap_reason"] = (
            f"真实诱饵偏好属于{true_name}，题干把偏好归到了关系人物{relationship_wrong_name}身上。"
        )
        payload["reasonable_answer"] = (
            f"历史中没有说明{relationship_wrong_name}{tail.rstrip('？?')}；"
            f"只知道{true_name}的相关偏好是：{true_pref}。"
        )
        return payload

    if adv_type == "attribute_slot_swap":
        payload["Q"] = f"{true_name}提到的{wrong_object}最符合哪一项？"
        opts, ans = _fallback_options(
            f"偏好与{subcategory}类似的{wrong_object}",
            f"对{wrong_object}非常讲究",
            f"对{wrong_object}没有明显倾向",
            refusal_slot,
        )
        payload["options"] = opts
        payload["A"] = ans
        payload["adversarial_answer"] = f"偏好与{subcategory}类似的{wrong_object}"
        payload["trap_reason"] = (
            f"真实信息支持的是“{subcategory}”下的偏好，题干把对象槽位改成了“{wrong_object}”。"
        )
        payload["reasonable_answer"] = (
            f"历史中没有可靠信息说明{true_name}提到过{wrong_object}；"
            f"可支持的偏好是：{true_pref}。"
        )
        return payload

    if adv_type == "category_type_swap":
        payload["Q"] = f"{true_name}在{wrong_object}方面更偏向哪一项？"
        opts, ans = _fallback_options(
            f"在{wrong_object}方面有自己的固定偏好",
            f"对{wrong_object}比较随性",
            f"在{wrong_object}方面跟随主流",
            refusal_slot,
        )
        payload["options"] = opts
        payload["A"] = ans
        payload["adversarial_answer"] = f"在{wrong_object}方面有自己的固定偏好"
        payload["trap_reason"] = (
            f"诱饵答案来自{subcategory}偏好，题干却换成了“{wrong_object}”这一不匹配类别。"
        )
        payload["reasonable_answer"] = (
            f"历史中没有说明{true_name}在{wrong_object}方面的偏好；"
            f"相关证据只支持：{true_pref}。"
        )
        return payload

    if adv_type == "lexical_concept_swap":
        payload["Q"] = f"{true_name}所谓的“{loaded}”具体指什么？"
        opts, ans = _fallback_options(base_adv_answer, base_distractors[0], base_distractors[1], refusal_slot)
        payload["options"] = opts
        payload["A"] = ans
        payload["adversarial_answer"] = base_adv_answer
        payload["trap_reason"] = (
            f"题干把中性的偏好概念恶意改写成“{loaded}”，原始记忆并没有这个说法。"
        )
        payload["reasonable_answer"] = (
            f"历史中没有把{true_name}的偏好称为“{loaded}”；"
            f"更准确的说法是：{true_pref}。"
        )
        return payload

    if adv_type == "polarity_flip":
        payload["Q"] = f"{true_name}在{subcategory}方面最排斥哪一项？"
        opts, ans = _fallback_options(base_adv_answer, base_distractors[0], base_distractors[1], refusal_slot)
        payload["options"] = opts
        payload["A"] = ans
        payload["adversarial_answer"] = base_adv_answer
        payload["trap_reason"] = (
            "题干把正向偏好改成了负向排斥，容易诱导模型把喜欢的内容当成不喜欢的内容。"
        )
        payload["reasonable_answer"] = (
            f"历史中没有说明{true_name}最排斥哪类{subcategory}；"
            f"相反，证据支持她/他偏向：{true_pref}。"
        )
        return payload

    if adv_type == "false_presupposition":
        false_context = false_presupposition_context(category, subcategory)
        payload["Q"] = f"{true_name}{false_context}，最强调哪一项？"
        opts, ans = _fallback_options(base_adv_answer, base_distractors[0], base_distractors[1], refusal_slot)
        payload["options"] = opts
        payload["A"] = ans
        payload["adversarial_answer"] = base_adv_answer
        payload["trap_reason"] = (
            f"题干强行假设“{false_context}”发生过，但历史没有这个事件前提。"
        )
        payload["reasonable_answer"] = (
            f"历史中没有说明{true_name}{false_context}；"
            f"只能确认相关偏好是：{true_pref}。"
        )
        return payload

    if adv_type == "event_context_swap":
        other_event = pick_other_event(formatted_profile, matched_events)
        if other_event:
            context = context_phrase(other_event)
        else:
            context = "聊到另一个日常话题时"
        payload["Q"] = f"{true_name}{context}，{tail}"
        opts, ans = _fallback_options(base_adv_answer, base_distractors[0], base_distractors[1], refusal_slot)
        payload["options"] = opts
        payload["A"] = ans
        payload["adversarial_answer"] = base_adv_answer
        payload["trap_reason"] = (
            "诱饵答案来自另一个真实偏好证据，题干把它塞进了不匹配的事件语境。"
        )
        payload["reasonable_answer"] = (
            f"历史中没有说明{true_name}{context}{tail.rstrip('？?')}；"
            f"诱饵答案只可支持原偏好：{true_pref}。"
        )
        return payload

    payload["adversarial_type"] = "implicit_overclaim"
    payload["Q"] = f"{true_name}在对话里明确说过的“{subcategory}”习惯是哪一项？"
    adapted_adv = f"有意识地保持{subcategory}习惯"
    opts, ans = _fallback_options(
        adapted_adv,
        f"偶尔提到过{subcategory}相关话题",
        f"从未关注过{subcategory}方面",
        refusal_slot,
    )
    payload["options"] = opts
    payload["A"] = ans
    payload["adversarial_answer"] = adapted_adv
    payload["trap_reason"] = (
        "真实诱饵来自隐式线索（如背景音或图像边缘），题干却要求它是对话中明确说出的信息。"
    )
    payload["reasonable_answer"] = (
        f"历史中没有说明{true_name}在对话里明确说过这一点；"
        f"只能从隐式线索推测：{true_pref}。"
    )
    return payload


def build_question_payload(
    base_question: str,
    base_options: dict,
    item: dict,
    true_name: str,
    relationship_wrong_name: str | None,
    matched_events: list[dict],
    formatted_profile: dict,
    base_answer: str,
    refusal_slot: int,
    target_type: str,
) -> tuple[dict, int, int]:
    base_adversarial_answer = str(base_options.get(base_answer, "")).strip()
    other_event = pick_other_event(formatted_profile, matched_events)
    wrong_context = context_phrase(other_event) if other_event else "另一个不相关日常语境"
    relationship_candidates = relationship_wrong_name or "无"

    prompt = PROMPT_GEN_ADVERSARIAL.format(
        target_type=target_type,
        good_case=json.dumps(GOOD_CASES[target_type], ensure_ascii=False, indent=2),
        true_name=true_name,
        relationship_candidates=relationship_candidates,
        relationship_wrong_name=relationship_wrong_name or "无",
        category=item["category"],
        subcategory=item["subcategory"],
        preference=item["preference"],
        expression_type=item["expression_type"],
        evidence_sources=", ".join(item["evidence_sources"])
        if isinstance(item["evidence_sources"], list)
        else str(item["evidence_sources"]),
        analysis="\n".join(f"- {x}" for x in item["analysis"])
        if isinstance(item["analysis"], list)
        else str(item["analysis"]),
        base_question=base_question,
        adversarial_answer=base_adversarial_answer,
        base_options=json.dumps(base_options, ensure_ascii=False),
        evidence_summary=evidence_summary(matched_events),
        wrong_context=wrong_context,
    )

    fallback = build_question_payload_fallback(
        base_question,
        item,
        true_name,
        relationship_wrong_name,
        matched_events,
        formatted_profile,
        target_type,
        base_options,
        base_answer,
        refusal_slot,
    )

    try:
        data, tokens_in, tokens_out = call_llm(prompt, temperature=TEMPERATURE_GEN)
        payload = normalize_payload(data, target_type)
        if payload_is_valid(payload, target_type, relationship_wrong_name):
            payload["llm_generated"] = True
            return payload, tokens_in, tokens_out
        print(f"[{item['p_id']}-{item['pref_code']}] invalid LLM payload, fallback: {payload}")
    except Exception as exc:
        print(f"[{item['p_id']}-{item['pref_code']}] LLM generation failed, fallback: {exc}")

    fallback["llm_generated"] = False
    return fallback, 0, 0


