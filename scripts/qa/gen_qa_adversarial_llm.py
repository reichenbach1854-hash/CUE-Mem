def parse_profile_ids(value: str | None) -> set[int] | None:
    """Parse comma/space separated profile ids from CLI."""
    if not value:
        return None
    ids: set[int] = set()
    for part in re.split(r"[\s,]+", value.strip()):
        if not part:
            continue
        try:
            ids.add(int(part))
        except ValueError as exc:
            raise argparse.ArgumentTypeError(
                f"--only_profile_ids contains a non-integer value: {part!r}"
            ) from exc
    return ids

