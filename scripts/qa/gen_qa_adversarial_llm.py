def load_json_or_jsonl(path: Path) -> list:
    if not path.exists():
        return []
    return load_records(path)


def call_llm(prompt: str, temperature: float = TEMPERATURE_GEN) -> tuple[dict, int, int]:
    client = openai_client(
        api_key_env="CUE_MEM_LLM_API_KEY",
        base_url_env="CUE_MEM_LLM_BASE_URL",
        timeout=60.0,
    )
    last_err = None
    last_text = ""

    for _ in range(LLM_RETRIES):
        try:
            api_res = client.chat.completions.create(
                model=MODEL,
                messages=[{"role": "user", "content": prompt}],
                temperature=temperature,
                stream=True,
                stream_options={"include_usage": True},
            )
            text = ""
            usage_info = None
            for chunk in api_res:
                if chunk.choices:
                    text += message_content_to_text(chunk.choices[0].delta.content)
                if hasattr(chunk, "usage") and chunk.usage is not None:
                    usage_info = chunk.usage

            last_text = text
            cleaned = text.strip().replace("```json", "").replace("```", "").strip()
            data = json.loads(repair_json(cleaned))
            tokens_in = usage_value(usage_info, "prompt_tokens")
            tokens_out = usage_value(usage_info, "completion_tokens")
            return data, tokens_in, tokens_out
        except Exception as exc:
            last_err = exc
            print(f"[call_llm] Error: {exc}; raw_tail={last_text[-200:]}")

    raise RuntimeError(f"call_llm failed after {LLM_RETRIES} attempts: {last_err}")


def profile_name(profile: dict) -> str:
    basic = profile.get("Basic") or {}
    return str(basic.get("name") or profile.get("name") or f"用户{profile.get('id', '')}")


def relationship_names(profile: dict) -> list[str]:
    basic = profile.get("Basic") or {}
    relationships = basic.get("Relationship") or []
    names = []
    for rel in relationships:
        name = str(rel.get("name", "")).strip()
        if name and name not in names:
            names.append(name)
    return names


def preference_items(profile: dict) -> list[dict]:
    out = []
    p_id = int(profile.get("id", len(out)))
    for category in CATEGORIES:
        prefs = profile.get(category) or []
        for idx, pref in enumerate(prefs):
            out.append(
                {
                    "p_id": p_id,
                    "category": category,
                    "pref_idx": idx,
                    "pref_code": f"{category}-{idx}",
                    "subcategory": pref.get("subcategory", ""),
                    "preference": pref.get("preference", ""),
                    "expression_type": pref.get("expression_type", ""),
                    "evidence_sources": pref.get("evidence_sources", []),
                    "analysis": pref.get("analysis", []),
                }
            )
    return out


def collect_preference_events(formatted_profile: dict, pref_code: str) -> list[dict]:
    events = []
    for event in formatted_profile.get("events", []) or []:
        codes = []
        codes.extend(event.get("explicit_preferences_reflected", []) or [])
        codes.extend(event.get("implicit_preferences_reflected", []) or [])
        if pref_code in codes:
            events.append(event)
    return events


def collect_valid_clue_keys(events: list[dict]) -> set[str]:
    valid = set()
    for event in events:
        for turn in event.get("dialog_list", []) or []:
            round_id = turn.get("round")
            if isinstance(round_id, str) and round_id:
                valid.add(round_id)
            for key in turn:
                if key.endswith(".png") or key.endswith(".wav"):
                    valid.add(key)
    return valid


def fallback_clues(events: list[dict], expression_type: str) -> list[str]:
    clues = []
    for event in events:
        for turn in event.get("dialog_list", []) or []:
            if expression_type == "implicit":
                for key in turn:
                    if key.endswith(".wav") or key.endswith(".png"):
                        clues.append(key)
            else:
                round_id = turn.get("round")
                if round_id:
                    clues.append(round_id)
                for key in turn:
                    if key.endswith(".png"):
                        clues.append(key)
            if len(clues) >= 3:
                return dedupe(clues)
    return dedupe(clues)


def dedupe(values: list[str]) -> list[str]:
    out = []
    for value in values:
        if value and value not in out:
            out.append(value)
    return out


def filter_clues(raw_clues: list, events: list[dict], expression_type: str) -> list[str]:
    valid = collect_valid_clue_keys(events)
    clues = []
    for clue in raw_clues or []:
        if isinstance(clue, str) and clue in valid and clue not in clues:
            clues.append(clue)
    return clues or fallback_clues(events, expression_type)


def event_date_place(event: dict) -> str:
    scene = (event.get("scene_description") or "").strip()
    parts = scene.split(";", 2)
    if len(parts) >= 2:
        return f"{parts[0]}，{parts[1]}"
    if parts and parts[0]:
        return parts[0]
    return event.get("session_id", "某次记录")


def short_phrase(text: str, limit: int = 34) -> str:
    value = " ".join(str(text or "").replace("\n", " ").split())
    value = value.strip(" ，。；;、")
    if len(value) <= limit:
        return value
    return value[:limit].rstrip(" ，。；;、") + "..."


def event_hint(event: dict) -> str:
    """Return a natural event anchor without explicit date/place wording."""
    for key in ("explicit_preferences", "implicit_preferences"):
        prefs = event.get(key) or []
        if prefs:
            pref = prefs[0]
            category = str(pref.get("category") or "")
            subcategory = str(pref.get("subcategory") or "").strip()
            content = pref.get("content") or pref.get("subcategory") or ""
            if content:
                bits = [bit.strip() for bit in str(content).split(";") if bit.strip()]
                if category.startswith("Relationship"):
                    relation = subcategory or (bits[0] if bits else "关系人物")
                    name = bits[1] if len(bits) > 1 else ""
                    label = f"{relation}{name}" if name and name not in relation else relation
                    return f"和{label}互动的那次分享"
                if category.startswith("BasicPets"):
                    pet_name = bits[0] if bits else "宠物"
                    return f"和宠物{pet_name}相处的那次分享"
                return f"围绕“{short_phrase(content)}”展开的那次分享"

    scene = (event.get("scene_description") or "").strip()
    parts = scene.split(";", 2)
    detail = parts[2] if len(parts) >= 3 else scene
    first_sentence = detail.split("。", 1)[0]
    return f"那次关于“{short_phrase(first_sentence)}”的分享"


def pick_other_event(formatted_profile: dict, matched_events: list[dict]) -> dict | None:
    matched_ids = {e.get("session_id") for e in matched_events}
    for event in formatted_profile.get("events", []) or []:
        if event.get("session_id") not in matched_ids:
            return event
    return None


def event_text(event: dict) -> str:
    parts = [
        event.get("scene_description") or "",
        event.get("user_shared_image_description") or "",
        event.get("background_audio_info") or "",
        event.get("human_speech_content") or "",
    ]
    for turn in event.get("dialog_list", []) or []:
        parts.append(str(turn.get("user", "")))
        parts.append(str(turn.get("assistant", "")))
    return "\n".join(parts)


def compact_event_summary(event: dict) -> str:
    scene = event.get("scene_description") or ""
    parts = scene.split(";", 2)
    scene_body = parts[2] if len(parts) >= 3 else scene
    lines = []
    if scene_body:
        lines.append(f"场景/事件: {short_phrase(scene_body, 160)}")
    image = event.get("user_shared_image_description")
    if image and image != "none":
        lines.append(f"图像: {short_phrase(image, 120)}")
    audio = event.get("background_audio_info")
    if audio and audio != "none":
        lines.append(f"背景音: {short_phrase(audio, 120)}")
    speech = event.get("human_speech_content")
    if speech and speech != "none":
        lines.append(f"人声: {short_phrase(speech, 100)}")

    turns = []
    for turn in event.get("dialog_list", []) or []:
        user = str(turn.get("user", "")).strip()
        assistant = str(turn.get("assistant", "")).strip()
        if user:
            turns.append(f"用户: {short_phrase(user, 70)}")
        if assistant:
            turns.append(f"助手: {short_phrase(assistant, 70)}")
        if len(turns) >= 4:
            break
    if turns:
        lines.append("对话片段: " + " / ".join(turns))
    return "\n".join(lines)


def evidence_summary(events: list[dict], limit: int = 2) -> str:
    if not events:
        return "无"
    chunks = []
    for idx, event in enumerate(events[:limit], start=1):
        chunks.append(f"[证据{idx}]\n{compact_event_summary(event)}")
    return "\n\n".join(chunks)


def normalize_payload(data: dict, target_type: str) -> dict:
    raw_options = data.get("options") or {}
    options = {}
    for label in OPTION_LABELS:
        val = raw_options.get(label)
        if isinstance(val, str) and val.strip():
            options[label] = val.strip()

    return {
        "adversarial_type": str(data.get("adversarial_type") or target_type).strip(),
        "Q": str(data.get("Q") or data.get("question") or "").strip(),
        "options": options if sorted(options) == OPTION_LABELS else {},
        "A": str(data.get("A") or "").strip(),
        "adversarial_answer": str(data.get("adversarial_answer") or "").strip(),
        "trap_reason": str(data.get("trap_reason") or data.get("rationale") or "").strip(),
        "reasonable_answer": str(data.get("reasonable_answer") or "").strip(),
    }


def payload_is_valid(payload: dict, target_type: str, relationship_wrong_name: str | None) -> bool:
    q = payload.get("Q", "")
    if payload.get("adversarial_type") != target_type:
        return False
    if not q or not payload.get("trap_reason") or not payload.get("reasonable_answer"):
        return False
    if any(marker in q for marker in ["这段记录", "memory clue", "session", "回想某次分享"]):
        return False
    if re.search(r"\d{2}/\d{2}/\d{4}", q):
        return False
    if target_type == "person_owner_swap":
        if not (relationship_wrong_name and relationship_wrong_name in q):
            return False

    options = payload.get("options", {})
    answer = payload.get("A", "")
    adv_ans = payload.get("adversarial_answer", "")
    if options:
        if sorted(options) != OPTION_LABELS:
            return False
        refusal_opts = [k for k, v in options.items() if v == REFUSAL_TEXT]
        if len(refusal_opts) != 1:
            return False
        if answer and answer != refusal_opts[0]:
            return False
        if adv_ans and adv_ans not in options.values():
            return False
    return True


def pick_relationship_swap_name(
    profile: dict,
    item: dict,
    matched_events: list[dict],
) -> str | None:
    """Pick a wrong subject only from the current user's Relationship list.

    In this benchmark, subject-swap adversarial questions should not swap
    between different benchmark characters.  Prefer a relationship person who
    is absent from the lure events so the mismatch stays clean.
    """
    names = relationship_names(profile)
    if not names:
        return None

    event_blob = "\n".join(event_text(event) for event in matched_events)
    absent_names = [name for name in names if name not in event_blob]
    candidates = absent_names or names
    idx = (item["p_id"] + item["pref_idx"] + CATEGORIES.index(item["category"])) % len(candidates)
    return candidates[idx]


def subject_tail(question: str, subcategory: str) -> str:
    q = (question or "").strip()
    prefixes = [
        "该用户",
        "这位用户",
        "用户",
        "此用户",
    ]
    for prefix in prefixes:
        if q.startswith(prefix):
            tail = q[len(prefix):].lstrip()
            return tail or f"在{subcategory}方面更符合哪一项？"
    if subcategory:
        return f"在“{subcategory}”方面更符合哪一项？"
    return "更符合哪一项？"


def context_phrase(event: dict) -> str:
    for key in ("explicit_preferences", "implicit_preferences"):
        prefs = event.get(key) or []
        if not prefs:
            continue
        pref = prefs[0]
        category = str(pref.get("category") or "")
        subcategory = str(pref.get("subcategory") or "").strip()
        content = pref.get("content") or subcategory or ""
        bits = [bit.strip() for bit in str(content).split(";") if bit.strip()]
        if category.startswith("Relationship"):
            relation = subcategory or (bits[0] if bits else "关系人物")
            name = bits[1] if len(bits) > 1 else ""
            label = f"{relation}{name}" if name and name not in relation else relation
            return f"和{label}互动时"
        if category.startswith("BasicPets"):
            pet_name = bits[0] if bits else "宠物"
            return f"和宠物{pet_name}相处时"
        if content:
            return f"聊到“{short_phrase(content, 24)}”时"
    return "那次日常分享里"


